"""Utility functions used by multiple consumers."""

from contextlib import suppress
from functools import wraps
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from collections.abc import Awaitable, Callable, Iterable
    from typing import Concatenate

    from asgi_types import (
        ASGIReceiveCallable,
        ASGISendCallable,
        ASGISendEvent,
        HTTPScope,
    )


type HTTPApplication = Callable[
    [HTTPScope, ASGIReceiveCallable, ASGISendCallable],
    Awaitable[None],
]
"""A type alias for an HTTP request handler."""

type HTTPApplicationMethodExt[Cls, **Args] = Callable[
    Concatenate[Cls, HTTPScope, ASGIReceiveCallable, ASGISendCallable, Args],
    Awaitable[None],
]
"""A type alias for an HTTP request handler method with extra parameters."""


class _PreventBodyError(Exception):
    """
    Raised after response headers are sent to prevent the response body from being sent.

    This is used to support HEAD and OPTIONS requests.
    """

    __slots__ = ()


def acceptable(mime_type: bytes, headers: Iterable[tuple[bytes, bytes]]) -> bool:
    """
    Check whether a given MIME type is acceptable to a client.

    :param mime_type: The MIME type the application is considering sending.
    :param headers: The request headers.
    :return: True if :param mime_type: is acceptable according to :param scope:’s Accept
        header, or False if not.
    """
    if (semi_pos := mime_type.find(b";")) != -1:
        mime_type = mime_type[:semi_pos]
    main_type = mime_type[: mime_type.find(b"/")]
    partial_wildcard = main_type + b"/*"
    wanted = {mime_type, partial_wildcard, b"*/*"}
    for name, value in headers:
        if name.lower() == b"accept":
            parts = value.split(b",")
            for part in parts:
                cleaned = part
                if (semi_pos := cleaned.find(b";")) >= 0:
                    cleaned = cleaned[:semi_pos]
                cleaned = cleaned.strip()
                if cleaned in wanted:
                    return True
            return False
    return True


# https://github.com/pylint-dev/pylint/issues/9884
# pylint: disable-next=redefined-outer-name
def allows_method[Cls, **Args](
    method: str,
) -> Callable[
    [HTTPApplicationMethodExt[Cls, Args]],
    HTTPApplicationMethodExt[Cls, Args],
]:
    """
    Decorate an HTTP request handler to check that a certain HTTP method is used.

    Calls that do not use the proper method are automatically rejected with status code
    405 (Method Not Allowed) and do not invoke the wrapped handler. All calls,
    successful or not, have the Allow header added to the response automatically unless
    the wrapped handler provides it.

    If :param method: is GET, HEAD requests are also allowed, and the body is
    automatically prevented from being sent. The handler is aborted by an exception
    immediately after the headers are sent.

    If multiple decorators are attached to a handler that may generate responses, this
    one must be the outermost, so that a HEAD request whose response is generated by
    another decorator can be prevented from returning a body by this decorator. For
    example, if the response_content_type decorator is also attached, that decorator
    must appear after this one, so that, if response_content_type generates a 406 Not
    Acceptable response, this decorator can prevent the usual error response body from
    being sent.

    :param method: The required HTTP method.
    """
    all_allowed = {method, "OPTIONS"}
    if method == "GET":
        all_allowed.add("HEAD")
    allow_header = (b"allow", ", ".join(all_allowed).encode("UTF-8"))

    def decorator(
        app: HTTPApplicationMethodExt[Cls, Args],
    ) -> HTTPApplicationMethodExt[Cls, Args]:
        @wraps(app)
        async def inner(
            obj: Cls,
            scope: HTTPScope,
            receive: ASGIReceiveCallable,
            send: ASGISendCallable,
            *args: Args.args,
            **kwargs: Args.kwargs,
        ) -> None:
            if scope["method"] == "OPTIONS":
                await discard_request(receive)
                await send(
                    {
                        "type": "http.response.start",
                        "status": 204,
                        "headers": [allow_header],
                    },
                )
                await send({"type": "http.response.body", "body": b""})
                return

            is_head = scope["method"] == "HEAD"

            @wraps(send)
            async def wrapped_send(event: ASGISendEvent) -> None:
                if event["type"] == "http.response.start":
                    headers = list(event.get("headers", []))
                    if not any(k == b"allow" for (k, _) in headers):
                        headers.append(allow_header)
                    event = {**event, "headers": headers}
                await send(event)
                if is_head:
                    raise _PreventBodyError

            with suppress(_PreventBodyError):
                if scope["method"] not in all_allowed:
                    await discard_request(receive)
                    await send_error(wrapped_send, 405, "Method Not Allowed")
                    return
                await app(obj, scope, receive, wrapped_send, *args, **kwargs)
            if is_head:
                await send({"type": "http.response.body", "body": b""})

        return inner

    return decorator


async def discard_request(receive: ASGIReceiveCallable) -> None:
    """
    Read and discard the request body.

    :param receive: The receive callable.
    """
    more = True
    while more:
        event = await receive()
        event_type = event["type"]
        match event_type:
            case "http.disconnect":
                return
            case "http.request":
                more = event.get("more_body", False)
            case _:
                msg = f"Unexpected HTTP event {event_type}"
                raise ValueError(msg)


# https://github.com/pylint-dev/pylint/issues/9884
# pylint: disable-next=redefined-outer-name
def discards_request[Cls, **Args](
    app: Callable[Concatenate[Cls, HTTPScope, ASGISendCallable, Args], Awaitable[None]],
) -> HTTPApplicationMethodExt[Cls, Args]:
    """
    Decorate a method to read and discard the body before executing it.

    :param app: The method to decorate.
    """

    @wraps(app)
    async def inner(
        obj: Cls,
        scope: HTTPScope,
        receive: ASGIReceiveCallable,
        send: ASGISendCallable,
        *args: Args.args,
        **kwargs: Args.kwargs,
    ) -> None:
        await discard_request(receive)
        await app(obj, scope, send, *args, **kwargs)

    return inner


# https://github.com/pylint-dev/pylint/issues/9884
# pylint: disable-next=redefined-outer-name
def response_content_type[Cls, **Args](
    content_type: bytes,
) -> Callable[
    [HTTPApplicationMethodExt[Cls, Args]],
    HTTPApplicationMethodExt[Cls, Args],
]:
    """
    Decorate an HTTP request handler for a specific response body content type.

    Requests that have an Accept header that does not permit the specified content type
    will be rejected with status code 406 (Not Acceptable). Responses with status 200
    will automatically have a Content-Type header added, unless the handler already
    provides one.

    :param content_type: The content type.
    """
    ok = 200

    def decorator(
        app: HTTPApplicationMethodExt[Cls, Args],
    ) -> HTTPApplicationMethodExt[Cls, Args]:
        @wraps(app)
        async def inner(
            obj: Cls,
            scope: HTTPScope,
            receive: ASGIReceiveCallable,
            send: ASGISendCallable,
            *args: Args.args,
            **kwargs: Args.kwargs,
        ) -> None:
            if not acceptable(content_type, scope.get("headers", [])):
                await discard_request(receive)
                await send_error(send, 406, "Not Acceptable")
                return

            @wraps(send)
            async def wrapped_send(event: ASGISendEvent) -> None:
                if event["type"] == "http.response.start" and event["status"] == ok:
                    headers: list[tuple[bytes, bytes]] = list(event.get("headers", []))
                    if not any(k == b"content-type" for (k, _) in headers):
                        headers.append((b"content-type", content_type))
                    event = {**event, "headers": headers}
                await send(event)

            await app(obj, scope, receive, wrapped_send, *args, **kwargs)

        return inner

    return decorator


async def send_error(send: ASGISendCallable, status: int, message: str) -> None:
    """
    Send an HTTP error response.

    The caller must already have consumed all receive-body events.

    :param send: The event-send function.
    :param status: The HTTP status code.
    :param message: The message to display in the page.
    """
    body = f"""<!DOCTYPE HTML>
<html>
<head>
<title>{message}</title>
</head>
<body>
<h1>{message}</h1>
</body>
</html>
"""
    body = body.encode("UTF-8")
    await send(
        {
            "type": "http.response.start",
            "status": status,
            "headers": [
                (b"content-type", b"text/html; charset=utf-8"),
                (b"content-length", str(len(body)).encode("UTF-8")),
            ],
        },
    )
    await send({"type": "http.response.body", "body": body})


def unmodified(etag: bytes, headers: Iterable[tuple[bytes, bytes]]) -> bool:
    """
    Check whether sending a resource can be skipped because the client already has it.

    This function must only be called for GET requests.

    :param etag: The ETag value of the resource, including the quotation marks.
    :param headers: The request headers.
    """
    for name, value in headers:
        if name.lower() == b"if-none-match":
            for i in value.split(b","):
                part = i.strip()
                if part == etag:
                    return True
                part = part.removeprefix(b"W/")
                if part == etag:
                    return True
    return False
